function writeDocx(path) {
  try {
    writeFileSync(path, buffer);
    console.log(`Written ${path}`);
  } catch (error) {
    if (error && (error.code === 'EBUSY' || error.code === 'EPERM')) {
      const fallback = path.replace(/\.docx$/i, '_новый.docx');
      writeFileSync(fallback, buffer);
      console.warn(`Файл занят (закройте Word): ${path}`);
      console.log(`Written ${fallback}`);
      return;
    }
    throw error;
  }
}

