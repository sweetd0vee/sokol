function pngSize(buffer) {
  if (buffer.length < 24 || buffer.toString('ascii', 1, 4) !== 'PNG') {
    return { width: 1600, height: 900 };
  }
  return {
    width: buffer.readUInt32BE(16),
    height: buffer.readUInt32BE(20),
  };
}

function p(text, opts = {}) {
  return new Paragraph({
    spacing: { after: opts.after ?? 160, before: opts.before ?? 0 },
    alignment: opts.center ? AlignmentType.CENTER : AlignmentType.LEFT,
    children: [
      new TextRun({
        text,
        bold: opts.bold,
        italics: opts.italics,
        color: opts.color,
        size: opts.size ?? 22,
        font: 'Calibri',
      }),
    ],
  });
}

function rich(runs, opts = {}) {
  return new Paragraph({
    spacing: { after: opts.after ?? 160, before: opts.before ?? 0 },
    children: runs.map((run) =>
      new TextRun({
        text: run.text,
        bold: run.bold,
        italics: run.italics,
        color: run.color,
        size: run.size ?? 22,
        font: 'Calibri',
      }),
    ),
  });
}

function heading(text, level = HeadingLevel.HEADING_1, opts = {}) {
  return new Paragraph({
    text,
    heading: level,
    pageBreakBefore: Boolean(opts.pageBreak),
    spacing: { before: opts.pageBreak ? 80 : 320, after: 160 },
  });
}

function bullet(text) {
  return new Paragraph({
    numbering: { reference: 'guide-bullets', level: 0 },
    spacing: { after: 80 },
    children: [new TextRun({ text, font: 'Calibri', size: 22 })],
  });
}

function step(n, text) {
  return new Paragraph({
    spacing: { after: 80 },
    indent: { left: 200 },
    children: [
      new TextRun({ text: `${n}.  `, bold: true, font: 'Calibri', size: 22, color: NAVY }),
      new TextRun({ text, font: 'Calibri', size: 22 }),
    ],
  });
}

function caption(text) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 40, after: 200 },
    children: [new TextRun({ text, italics: true, color: MUTED, size: 18, font: 'Calibri' })],
  });
}

function loadImage(filename, { maxWidth = 620, maxHeight = 720, captionText, fallback } = {}) {
  const candidates = [filename, ...(fallback ?? [])];
  const path = candidates.map((name) => join(SCREENSHOTS_DIR, name)).find((candidate) => existsSync(candidate));
  if (!path) {
    return [
      p(`[Иллюстрация не найдена: ${filename}. Запустите npm run docs:analytics-screenshots]`, {
        italics: true,
        color: MUTED,
      }),
    ];
  }
  const data = readFileSync(path);
  const { width, height } = pngSize(data);
  const scale = Math.min(maxWidth / width, maxHeight / height);
  const blocks = [
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { before: 120, after: captionText ? 40 : 200 },
      children: [
        new ImageRun({
          data,
          transformation: {
            width: Math.max(120, Math.round(width * scale)),
            height: Math.max(80, Math.round(height * scale)),
          },
          type: 'png',
        }),
      ],
    }),
  ];
  if (captionText) {
    blocks.push(caption(captionText));
  }
  return blocks;
}

function luminance(hex) {
  const value = hex.replace('#', '');
  const r = Number.parseInt(value.slice(0, 2), 16);
  const g = Number.parseInt(value.slice(2, 4), 16);
  const b = Number.parseInt(value.slice(4, 6), 16);
  return (0.299 * r + 0.587 * g + 0.114 * b) / 255;
}

function cell(text, { header = false, width, shade, bold, color } = {}) {
  const fill = header ? TABLE_HEADER_FILL : shade;
  const textColor = header ? 'FFFFFF' : color ?? (fill && luminance(fill) < 0.55 ? 'FFFFFF' : '111827');
  return new TableCell({
    width: width ? { size: width, type: WidthType.DXA } : undefined,
    shading: fill ? { type: ShadingType.CLEAR, fill } : undefined,
    margins: { top: 60, bottom: 60, left: 80, right: 80 },
    verticalAlign: VerticalAlign.CENTER,
    children: [
      new Paragraph({
        children: [
          new TextRun({
            text,
            bold: header || bold,
            color: textColor,
            size: 20,
            font: 'Calibri',
          }),
        ],
      }),
    ],
  });
}

function simpleTable(headers, rows) {
  const colWidth = Math.floor(PAGE_WIDTH_DXA / headers.length);
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    columnWidths: headers.map(() => colWidth),
    rows: [
      new TableRow({
        tableHeader: true,
        children: headers.map((header) => cell(header, { header: true, width: colWidth })),
      }),
      ...rows.map((row, index) =>
        new TableRow({
          children: row.map((value) =>
            cell(String(value), {
              width: colWidth,
              shade: index % 2 === 1 ? TABLE_ALT_FILL : undefined,
            }),
          ),
        }),
      ),
    ],
  });
}

function kvTable(pairs) {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    columnWidths: [2600, 6426],
    rows: pairs.map(([key, value], index) =>
      new TableRow({
        children: [
          cell(key, { bold: true, width: 2600, shade: index % 2 === 1 ? TABLE_ALT_FILL : undefined }),
          cell(value, { width: 6426, shade: index % 2 === 1 ? TABLE_ALT_FILL : undefined }),
        ],
      }),
    ),
  });
}

function chartHeading(title) {
  return heading(title, HeadingLevel.HEADING_3);
}

function chartBlock({
  title,
  type,
  screenshot,
  screenshotFallback,
  meaning,
  formula,
  reads,
  decisions,
  notes,
}) {
  const blocks = [
    chartHeading(title),
    rich([{ text: 'Тип визуализации. ', bold: true }, { text: type }]),
    rich([{ text: 'Бизнес-смысл. ', bold: true }, { text: meaning }]),
  ];
  if (formula) {
    blocks.push(rich([{ text: 'Как считается. ', bold: true }, { text: formula }]));
  }
  if (reads?.length) {
    blocks.push(rich([{ text: 'Как читать.', bold: true }]));
    reads.forEach((item) => blocks.push(bullet(item)));
  }
  if (decisions?.length) {
    blocks.push(rich([{ text: 'Какие решения помогает принимать.', bold: true }]));
    decisions.forEach((item) => blocks.push(bullet(item)));
  }
  if (notes) {
    blocks.push(rich([{ text: 'Важно. ', bold: true, italics: true }, { text: notes, italics: true }]));
  }
  if (screenshot) {
    blocks.push(
      ...loadImage(screenshot, {
        maxWidth: 600,
        maxHeight: 420,
        captionText: `Пример: ${title}`,
        fallback: screenshotFallback,
      }),
    );
  }
  return blocks;
}

